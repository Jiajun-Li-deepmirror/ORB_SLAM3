"""Turn Kalibr imu-camera results into a splg_slam config snippet and a readable summary.

Reads <work>/kalibr-camchain-imucam.yaml (and the factory camchain for comparison), writes
<work>/splg_imu_override.yaml with imu.t_cam0_body_override / imu.time_offset_ms.

Conventions (checked against splg_slam):
  Kalibr cam0.T_cam_imu maps IMU-frame points into cam0 = splg's T_cam0_body (body -> cam0;
  cam0 is the infra1 optical frame, whose rectification rotation is identity on the D435i).
  Kalibr timeshift_cam_imu: t_imu = t_cam + shift  -> splg imu.time_offset_ms = shift * 1000
  (IMU timestamps running ahead of the camera's, subtracted from every IMU stamp).
"""
import sys
from pathlib import Path

import numpy as np
import yaml
from scipy.spatial.transform import Rotation

work = Path(sys.argv[1])
imucam = yaml.safe_load((work / "kalibr-camchain-imucam.yaml").read_text())
factory = yaml.safe_load((work / "kalibr-camchain-factory.yaml").read_text())
cam0 = imucam["cam0"]
T = np.array(cam0["T_cam_imu"], dtype=float)
shift_ms = 1000.0 * float(cam0.get("timeshift_cam_imu", 0.0))

# tf_static of this unit: identity rotation, translation (5.52, -5.10, -11.74) mm.
T_tf = np.eye(4)
T_tf[:3, 3] = [0.00552, -0.0051, -0.01174]
dR = Rotation.from_matrix(T[:3, :3] @ T_tf[:3, :3].T)
rotvec = np.degrees(dR.as_rotvec())

print("Kalibr T_cam0_imu:\n", np.array2string(T, precision=6, suppress_small=True))
print(f"rotation vs tf_static (identity): {np.linalg.norm(rotvec):.3f} deg, "
      f"rotvec in cam0 [x(pitch), y(yaw about vertical), z(roll)] = {np.round(rotvec, 3).tolist()} deg")
print(f"translation vs tf_static: {np.round((T[:3, 3] - T_tf[:3, 3]) * 1000, 2).tolist()} mm")
print(f"timeshift t_imu = t_cam + {shift_ms:.2f} ms for this recording's exposure "
      "(not exported: the offset moves by about -exposure/2; configs use time_offset_ms: 8.0)")
print("For reference, the floor-normal vs accelerometer offset measured from the SLAM "
      "datasets was about [1.23, -, 0.76] deg (x, -, z).")
if "cam1" in imucam and "T_cn_cnm1" in imucam["cam1"]:
    b_k = np.array(imucam["cam1"]["T_cn_cnm1"])[:3, 3]
    b_f = np.array(factory["cam1"]["T_cn_cnm1"])[:3, 3]
    print(f"stereo baseline: kalibr {np.linalg.norm(b_k) * 1000:.2f} mm vs factory {np.linalg.norm(b_f) * 1000:.2f} mm")
for name in ("cam0", "cam1"):
    if name in imucam:
        k, f = imucam[name]["intrinsics"], factory[name]["intrinsics"]
        print(f"{name} intrinsics kalibr {np.round(k, 2).tolist()} vs factory {np.round(f, 2).tolist()}, "
              f"distortion {np.round(imucam[name]['distortion_coeffs'], 4).tolist()}")

# The image stamp marks the end of exposure, so the IMU-vs-image offset shifts by about
# -exposure/2 (measured on the SLAM recordings: +6.3 ms at 0.45 ms exposure, +1.0 ms at 10.9 ms).
# Kalibr's value is only valid for this recording's exposure, so it is not exported as a setting.
snippet = {"imu": {"t_cam0_body_override": np.round(T, 9).tolist()}}
out = work / "splg_imu_override.yaml"
out.write_text("# Generated by kalibr_to_splg.py from kalibr-camchain-imucam.yaml; merge into the\n"
               "# imu: section of a copy of configs/realsense_current_stereo_imu.yaml.\n"
               f"# Kalibr timeshift for THIS recording: t_imu = t_cam + {shift_ms:.2f} ms. It depends on\n"
               "# exposure (stamp = end of exposure), so keep imu.time_offset_ms measured on the SLAM data.\n"
               + yaml.safe_dump(snippet, sort_keys=False))
print(f"wrote {out}")
for report in ("kalibr-results-imucam.txt", "kalibr-report-imucam.pdf"):
    if (work / report).exists():
        print(f"see {work / report}")
